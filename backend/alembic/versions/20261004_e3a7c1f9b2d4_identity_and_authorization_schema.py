# Users are never deleted (disable them), so every actor and audit reference
# stays valid. Their id and username never change.
USER_GUARD = """
CREATE FUNCTION guard_user_changes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'users cannot be deleted; disable them instead'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF (NEW.id, NEW.username, NEW.created_at) IS DISTINCT FROM
       (OLD.id, OLD.username, OLD.created_at) THEN
        RAISE EXCEPTION 'a user''s id and username are immutable'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$
"""

