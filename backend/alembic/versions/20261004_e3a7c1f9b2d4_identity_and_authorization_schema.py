# The event time is the database's; metadata is a flat object of scalar values
# with plain keys, at most 4 KB, and keys that name secrets or captured
# content are refused (the application only writes allowlisted keys).
AUDIT_INSERT_CHECK = r"""
CREATE FUNCTION check_audit_event_insert() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    item record;
BEGIN
    NEW.occurred_at := now();
    IF jsonb_typeof(NEW.metadata) <> 'object' THEN
        RAISE EXCEPTION 'audit metadata must be a JSON object'
            USING ERRCODE = 'check_violation';
    END IF;
    IF octet_length(NEW.metadata::text) > 4096 THEN
        RAISE EXCEPTION 'audit metadata is limited to 4 KB'
            USING ERRCODE = 'check_violation';
    END IF;
    FOR item IN SELECT key, value FROM jsonb_each(NEW.metadata) LOOP
        IF item.key !~ '^[a-z][a-z0-9_]{0,39}$' THEN
            RAISE EXCEPTION 'audit metadata keys must be lower_snake_case'
                USING ERRCODE = 'check_violation';
        END IF;
        IF item.key ~ ('(password|passwd|secret|token|cookie|authorization|credential|'
                       || 'private_key|api_key|body|header)') THEN
            RAISE EXCEPTION 'audit metadata key % may hold secrets or captured content', item.key
                USING ERRCODE = 'check_violation';
        END IF;
        IF jsonb_typeof(item.value) NOT IN ('string', 'number', 'boolean', 'null') THEN
            RAISE EXCEPTION 'audit metadata values must be scalars'
                USING ERRCODE = 'check_violation';
        END IF;
        IF jsonb_typeof(item.value) = 'string' AND length(item.value #>> '{}') > 256 THEN
            RAISE EXCEPTION 'audit metadata strings are limited to 256 characters'
                USING ERRCODE = 'check_violation';
        END IF;
    END LOOP;
    RETURN NEW;
END;
$$
"""

