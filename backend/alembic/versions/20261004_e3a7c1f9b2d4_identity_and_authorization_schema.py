# Once a project has members it keeps at least one owner until the project is
# deleted (its memberships cascade). Checked when the transaction commits, so
# ownership can be handed over within one transaction; an advisory lock per
# project serializes concurrent checks, so two transactions removing different
# owners cannot both succeed. Legacy projects that never had members are not
# affected: the trigger only runs for membership rows.
LAST_OWNER_CHECK = """
CREATE FUNCTION check_project_keeps_owner() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    pid uuid := COALESCE(NEW.project_id, OLD.project_id);
BEGIN
    PERFORM pg_advisory_xact_lock(hashtextextended('project_members:' || pid::text, 0));
    IF EXISTS (SELECT 1 FROM projects WHERE id = pid)
       AND NOT EXISTS (
           SELECT 1 FROM project_members WHERE project_id = pid AND role = 'owner'
       ) THEN
        RAISE EXCEPTION 'a project must keep at least one owner'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NULL;
END;
$$
"""

