# A retest report is only ever created for a completed comparison (completed
# comparisons never change). Its content is frozen from creation; while queued
# or generating only its processing fields may change, along the allowed status
# transitions; completed and failed reports never change; reports are never
# deleted; a report completes only with exactly the artifacts it requested.
REPORT_GUARD = """
CREATE FUNCTION guard_retest_report_changes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NOT EXISTS (
            SELECT 1 FROM comparisons c WHERE c.id = NEW.comparison_id AND c.status = 'completed'
        ) THEN
            RAISE EXCEPTION 'retest reports require a completed comparison'
                USING ERRCODE = 'restrict_violation';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'retest reports cannot be deleted'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.status IN ('completed', 'failed') THEN
        RAISE EXCEPTION 'completed and failed retest reports are immutable'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF NOT (
        (OLD.status = 'queued' AND NEW.status IN ('queued', 'generating', 'failed'))
        OR (OLD.status = 'generating' AND NEW.status IN ('generating', 'completed', 'failed'))
    ) THEN
        RAISE EXCEPTION 'invalid retest report status transition'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF (NEW.id, NEW.number, NEW.comparison_id, NEW.target_id, NEW.baseline_assessment_id,
        NEW.baseline_scan_id, NEW.current_assessment_id, NEW.current_scan_id, NEW.kind,
        NEW.title, NEW.prepared_by, NEW.reviewed_by, NEW.classification, NEW.formats,
        NEW.template_id, NEW.template_version, NEW.template_hash, NEW.schema_version,
        NEW.snapshot, NEW.snapshot_sha256, NEW.content_sha256, NEW.created_at)
       IS DISTINCT FROM
       (OLD.id, OLD.number, OLD.comparison_id, OLD.target_id, OLD.baseline_assessment_id,
        OLD.baseline_scan_id, OLD.current_assessment_id, OLD.current_scan_id, OLD.kind,
        OLD.title, OLD.prepared_by, OLD.reviewed_by, OLD.classification, OLD.formats,
        OLD.template_id, OLD.template_version, OLD.template_hash, OLD.schema_version,
        OLD.snapshot, OLD.snapshot_sha256, OLD.content_sha256, OLD.created_at) THEN
        RAISE EXCEPTION 'retest report content is immutable'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF NEW.status = 'completed' AND
       (SELECT array_agg(a.format::text ORDER BY a.format)
          FROM retest_report_artifacts a WHERE a.report_id = NEW.id)
       IS DISTINCT FROM
       (SELECT array_agg(f::text ORDER BY f) FROM unnest(NEW.formats) AS f) THEN
        RAISE EXCEPTION 'a completed retest report must have exactly its requested artifacts'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$
"""

ARTIFACT_GUARD = """
CREATE FUNCTION guard_retest_report_artifact_changes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'retest report artifacts are immutable'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM retest_reports r
        WHERE r.id = NEW.report_id AND r.status = 'generating' AND NEW.format = ANY(r.formats)
    ) THEN
        RAISE EXCEPTION
            'artifacts can only be added to a generating retest report, in a requested format'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$
"""

EVIDENCE_GUARD = """
CREATE FUNCTION guard_retest_report_evidence_changes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'retest report evidence links are immutable'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM retest_reports r WHERE r.id = NEW.report_id AND r.status = 'queued'
    ) THEN
        RAISE EXCEPTION 'evidence links can only be added while the retest report is queued'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$
"""

