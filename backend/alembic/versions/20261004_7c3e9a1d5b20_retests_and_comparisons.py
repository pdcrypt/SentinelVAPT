# A comparison's inputs never change; it moves queued -> completed | failed
# once; completed and failed comparisons never change; nothing is deleted.
COMPARISON_GUARD = """
CREATE FUNCTION guard_comparison_changes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'comparisons cannot be deleted'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.status IN ('completed', 'failed') THEN
        RAISE EXCEPTION 'completed and failed comparisons are immutable'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF NEW.status NOT IN ('queued', 'completed', 'failed') THEN
        RAISE EXCEPTION 'invalid comparison status transition'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF (NEW.id, NEW.target_id, NEW.baseline_assessment_id, NEW.baseline_scan_id,
        NEW.baseline_run_id, NEW.current_assessment_id, NEW.current_scan_id,
        NEW.current_run_id, NEW.previous_comparison_id, NEW.policy_version, NEW.created_at)
       IS DISTINCT FROM
       (OLD.id, OLD.target_id, OLD.baseline_assessment_id, OLD.baseline_scan_id,
        OLD.baseline_run_id, OLD.current_assessment_id, OLD.current_scan_id,
        OLD.current_run_id, OLD.previous_comparison_id, OLD.policy_version, OLD.created_at) THEN
        RAISE EXCEPTION 'comparison inputs are immutable'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$
"""

# Records are written once, by the worker computing the comparison, while it
# is still queued (the same transaction then completes it).
RECORD_GUARD = """
CREATE FUNCTION guard_comparison_record_changes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'comparison records are immutable'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM comparisons c WHERE c.id = NEW.comparison_id AND c.status = 'queued'
    ) THEN
        RAISE EXCEPTION 'comparison records can only be added while the comparison is queued'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$
"""

# Coverage evidence backs FIXED / DISMISSED records only, at most 25 each.
# The limit (25) matches MAX_COVERAGE_EVIDENCE.
COVERAGE_GUARD = """
CREATE FUNCTION guard_comparison_coverage_changes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'comparison coverage evidence is immutable'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM comparisons c WHERE c.id = NEW.comparison_id AND c.status = 'queued'
    ) THEN
        RAISE EXCEPTION 'coverage evidence can only be added while the comparison is queued'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM comparison_records r
        WHERE r.comparison_id = NEW.comparison_id AND r.fingerprint = NEW.fingerprint
          AND r.state IN ('fixed', 'dismissed')
    ) THEN
        RAISE EXCEPTION 'coverage evidence is only recorded for fixed or dismissed records'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF (SELECT count(*) FROM comparison_coverage_evidence e
        WHERE e.comparison_id = NEW.comparison_id AND e.fingerprint = NEW.fingerprint)
       >= 25 THEN
        RAISE EXCEPTION 'at most 25 coverage evidence records per record'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$
"""

