"""Generated documentation and the rule metadata lockfile.

    python -m sentinel_analysis.catalog docs   > ../docs/rules.md
    python -m sentinel_analysis.catalog lock   # rewrite rule_metadata.lock.json

The lockfile maps "RULE-ID@version" to the hash of that version's metadata.
A test fails if a rule's metadata changes without a version bump. Entries for
older versions are kept (append-only history).
"""

import json
import sys
from pathlib import Path

from sentinel_analysis.engine import RULESET_VERSION
from sentinel_analysis.rules import REGISTRY
from sentinel_analysis.taxonomy import (
    CWE,
    CWE_VERSION,
    OWASP_TOP10_2025,
    OWASP_TOP10_EDITION,
    WSTG_EDITION,
    WSTG_V42,
)

LOCKFILE = Path(__file__).with_name("rule_metadata.lock.json")


def render_markdown() -> str:
    lines = [
        "# Rule catalog",
        "",
        "<!-- Generated by `python -m sentinel_analysis.catalog docs`. Do not edit by hand. -->",
        "",
        f"Ruleset version: `{RULESET_VERSION}`. Taxonomies: {OWASP_TOP10_EDITION}, "
        f"{WSTG_EDITION}, {CWE_VERSION} (see [taxonomy.md](taxonomy.md)).",
        "",
        "Severity is project-defined (not CVSS). Confidence says how sure the observed "
        "condition holds; detection type says whether a human must verify it. "
        "**PROVES** is exactly what the evidence establishes; **DOES NOT PROVE** is what "
        "would need active testing, application context or manual verification.",
        "",
        "| ID | v | Title | Severity | Confidence | Detection | Subject |",
        "| -- | - | ----- | -------- | ---------- | --------- | ------- |",
    ]
    for rule in REGISTRY:
        m = rule.meta
        lines.append(
            f"| {m.id} | {m.version} | {m.title} | {m.severity} | {m.confidence} | "
            f"{m.detection_type} | {m.subject_type} |"
        )
    for rule in REGISTRY:
        m = rule.meta
        owasp = ", ".join(f"{i} {OWASP_TOP10_2025[i]}" for i in m.owasp_top10) or "none"
        wstg = ", ".join(f"{i} {WSTG_V42[i].title}" for i in m.wstg) or "none"
        cwe = ", ".join(f"CWE-{i} {CWE[i].title}" for i in m.cwe) or "none"
        lines += [
            "",
            f"## {m.id}: {m.title} (v{m.version})",
            "",
            m.description,
            "",
            f"- **Severity / confidence / detection:** {m.severity} / {m.confidence} / "
            f"{m.detection_type}",
            f"- **Subject:** {m.subject_type}",
            f"- **PROVES:** {m.proves}",
            f"- **DOES NOT PROVE:** {m.does_not_prove}",
            f"- **Remediation:** {m.remediation}",
            f"- **OWASP Top 10:2025:** {owasp}",
            f"- **WSTG v4.2:** {wstg}",
            f"- **CWE:** {cwe}",
        ]
    return "\n".join(lines) + "\n"


def current_lock_entries() -> dict[str, str]:
    return {f"{r.meta.id}@{r.meta.version}": r.meta.metadata_hash() for r in REGISTRY}


def read_lockfile() -> dict[str, str]:
    data: dict[str, str] = json.loads(LOCKFILE.read_text(encoding="utf-8"))
    return data


def write_lockfile() -> None:
    existing = read_lockfile() if LOCKFILE.exists() else {}
    merged = {**existing, **current_lock_entries()}
    LOCKFILE.write_text(json.dumps(merged, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def main(argv: list[str]) -> int:
    command = argv[0] if argv else "docs"
    if command == "docs":
        sys.stdout.write(render_markdown())
    elif command == "lock":
        write_lockfile()
    else:
        sys.stderr.write("usage: python -m sentinel_analysis.catalog [docs|lock]\n")
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
