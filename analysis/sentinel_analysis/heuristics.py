"""Documented heuristics. Each one is explicit, deterministic and tested, and
the rules that use them report at most medium confidence.
"""

import re

# --- Session-like cookie names --------------------------------------------------------
#
# A name is session-like if, case-insensitively:
#   1. it equals one of SESSION_COOKIE_NAMES, or
#   2. it starts with one of SESSION_COOKIE_PREFIXES, or
#   3. after splitting on "-", "_" and ".", one whole token is in
#      SESSION_COOKIE_TOKENS (whole tokens only: "sidebar" does not match "sid").
#
# Expected false positives: preference/analytics cookies such as
# "session_theme" or "auth_redirect"; CSRF cookies named "*_token" that are
# meant to be readable by scripts.
# Expected false negatives: session cookies with opaque names ("x9f2"), or
# names using other words ("ident", "login").

SESSION_COOKIE_NAMES = frozenset(
    {
        "phpsessid",
        "jsessionid",
        "asp.net_sessionid",
        "laravel_session",
        "ci_session",
        "connect.sid",
        "rack.session",
        "sessionid",
        "session",
        "sid",
        "_session_id",
    }
)
SESSION_COOKIE_PREFIXES = ("aspsessionid",)
SESSION_COOKIE_TOKENS = frozenset({"session", "sess", "sessid", "sid", "auth", "token", "jwt"})

_TOKEN_SPLIT = re.compile(r"[-_.]")
MAX_COOKIE_NAME = 200


def is_session_like_cookie(name: str) -> bool:
    lowered = name[:MAX_COOKIE_NAME].strip().lower()
    if not lowered:
        return False
    if lowered in SESSION_COOKIE_NAMES or lowered.startswith(SESSION_COOKIE_PREFIXES):
        return True
    return any(token in SESSION_COOKIE_TOKENS for token in _TOKEN_SPLIT.split(lowered))


# --- Error / stack-trace text --------------------------------------------------------
#
# Plain substring markers (no regular expressions). Each is characteristic of a
# runtime error or stack trace from a common platform. Matching proves only that
# the text is present in the stored excerpt.

ERROR_MARKERS: tuple[tuple[str, str], ...] = (
    ("python_traceback", "Traceback (most recent call last)"),
    ("java_exception", 'Exception in thread "'),
    ("java_stack_frame", "\tat java."),
    ("java_stack_frame", "\n    at java."),
    ("dotnet_exception", "System.NullReferenceException"),
    ("dotnet_server_error", "Server Error in '/' Application"),
    ("php_fatal_error", "Fatal error</b>:"),
    ("php_fatal_error", "PHP Fatal error:"),
    ("php_stack_trace", "Stack trace:\n#0"),
    ("sql_error", "You have an error in your SQL syntax"),
    ("sql_error", "SQLSTATE["),
    ("sql_error", "ORA-00933"),
    ("sql_error", "psycopg2.errors."),
    ("werkzeug_debugger", "Werkzeug Debugger"),
    ("django_debug", "You're seeing this error because you have <code>DEBUG = True</code>"),
    ("node_stack_frame", "\n    at Object.<anonymous>"),
)


def error_markers_in(text: str) -> tuple[str, ...]:
    """Names of error markers present in text, sorted and de-duplicated."""
    return tuple(sorted({name for name, marker in ERROR_MARKERS if marker in text}))


# --- Directory listing pages -----------------------------------------------------------
#
# Titles generated by common auto-index implementations (Apache/nginx "Index
# of /...", Python http.server "Directory listing for /...").

DIRECTORY_TITLE_PREFIXES = ("index of /", "directory listing for /")


def looks_like_directory_listing(title: str | None, excerpt: str) -> bool:
    if title and title[:300].strip().lower().startswith(DIRECTORY_TITLE_PREFIXES):
        return True
    head = excerpt[:2048].lower()
    return any(f"<title>{prefix}" in head for prefix in DIRECTORY_TITLE_PREFIXES)
